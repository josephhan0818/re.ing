// Function to set the language
function setLanguage(lang) {
  document.documentElement.setAttribute('data-lang', lang);
  document.documentElement.lang = lang;

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      element.innerHTML = translations[lang][key];
    }
  });

  // Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      element.setAttribute('placeholder', translations[lang][key]);
    }
  });
}

// Function to handle language switching from dropdown/buttons
function switchLanguage(lang) {
    if (translations[lang]) {
        setLanguage(lang);
        localStorage.setItem('language', lang);
    }
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('language') || 'en'; // Default to English
  // Ensure the saved language is valid before setting it
  if (translations[savedLang]) {
    setLanguage(savedLang);
  } else {
    setLanguage('en');
  }

  // Example of how to set up language switchers
  const langSwitchers = document.querySelectorAll('[data-lang-switcher]');
  langSwitchers.forEach(switcher => {
    switcher.addEventListener('click', (event) => {
      event.preventDefault();
      const lang = switcher.getAttribute('data-lang-switcher');
      switchLanguage(lang);
    });
  });
});
